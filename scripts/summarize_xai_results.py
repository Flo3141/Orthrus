#!/usr/bin/env python3
"""
LaTeX tables of the xAI results (motif perturbation and channel ablation) of fine-tuned N-track Orthrus models.

Recursively scans a checkpoint directory (default: $ORTHRUS_BASE/checkpoints/orthrus) for runs with
fold_k/drach_summary.json or fold_k/xai_channel_summary.json. Each run gets up to two tables:
  - Motif perturbation: effect per fold, mean and SD across folds, shifts against the original prediction
  - Channel ablation: drop in Pearson r per fold, mean and SD across folds

Each run directory receives two files next to its fold_k directories:
  - xai_tables.tex: the tables of this run, for \\input in the thesis (needs the LaTeX packages booktabs and graphicx)
  - xai_tables_main.tex: standalone document that renders them (pdflatex xai_tables_main.tex in the run directory)

Usage:
  python summarize_xai_results.py
  python summarize_xai_results.py -d <checkpoint_dir>
"""

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Optional

import numpy as np

from util import CHECKPOINTS_DIR


MOTIF_FILE = "drach_summary.json"
ABLATION_FILE = "xai_channel_summary.json"
EFFECT_SCALE = 1e3  # Effects are small, the motif table shows them in units of 10^-3
TABLES_FILE = "xai_tables.tex"
DOCUMENT_FILE = "xai_tables_main.tex"
DOCUMENT_TEMPLATE = rf"""% Auto-generated by summarize_xai_results.py
% Render in this directory with: pdflatex {DOCUMENT_FILE}
\documentclass[11pt]{{article}}

\usepackage[T1]{{fontenc}}
\usepackage{{lmodern}} % Vector fonts instead of bitmap fonts in the PDF
\usepackage[a4paper,landscape,margin=2cm]{{geometry}} % Landscape: the motif table has 13 columns
\usepackage{{booktabs}} % \toprule, \midrule, \bottomrule, \addlinespace
\usepackage{{graphicx}} % \resizebox

\pagestyle{{empty}}

\begin{{document}}

\input{{{TABLES_FILE}}}

\end{{document}}
"""


def get_default_checkpoints_dir() -> Path:
    """Returns the cluster default dir if it exists, otherwise the local downloaded results."""
    if CHECKPOINTS_DIR.exists():
        return CHECKPOINTS_DIR
    return Path(__file__).resolve().parents[2] / "downloaded_results" / "checkpoints" / "orthrus"


def find_run_dirs(base_dir: Path) -> list:
    """All directories below base_dir (or base_dir itself) with at least one fold that has xAI results."""
    if not base_dir.exists():
        raise FileNotFoundError(f"[Error] Target directory does not exist: {base_dir}")
    return sorted({p.parent.parent for name in (MOTIF_FILE, ABLATION_FILE) for p in base_dir.rglob(f"fold_*/{name}")})


def load_fold_summaries(run_dir: Path, filename: str, required_key: str) -> tuple:
    """
    Returns ({fold: content of fold_k/<filename>} sorted by fold, number of ignored files). Ignored are results older
    than the training of their fold (retraining leaves old xAI files in place) and files of older script versions
    without required_key.
    """
    paths = {int(p.parent.name.split("_")[1]): p for p in run_dir.glob(f"fold_*/{filename}")}
    summaries, n_ignored = {}, 0
    for fold in sorted(paths):
        path = paths[fold]
        training_summary = path.parent / "training_summary.json"
        if training_summary.is_file() and path.stat().st_mtime < training_summary.stat().st_mtime:
            n_ignored += 1
            continue
        with open(path, "r", encoding="utf-8") as f:
            content = json.load(f)
        if required_key in content:
            summaries[fold] = content
        else:
            n_ignored += 1
    return summaries, n_ignored


# =============================================================================
# LaTeX helpers
# =============================================================================

def escape_latex(text: str) -> str:
    return text.replace("_", "\\_").replace("&", "\\&").replace("%", "\\%")


def signed(value: Optional[float], decimals: int = 1) -> str:
    return "--" if value is None else f"${value:+.{decimals}f}$"


def unsigned(value: Optional[float], decimals: int = 3) -> str:
    return "--" if value is None else f"${value:.{decimals}f}$"


def mean_sd(values: list, sign: bool, decimals: int) -> str:
    """
    Mean and SD of the available folds. np.std as in xai_analysis.py and drach_analysis.py, so that the numbers
    match the aggregated JSON files and plots.
    """
    available = [v for v in values if v is not None]
    if not available:
        return "--"
    mean = f"{np.mean(available):+.{decimals}f}" if sign else f"{np.mean(available):.{decimals}f}"
    return f"${mean} \\pm {np.std(available):.{decimals}f}$"


def mean_or_none(values: list) -> Optional[float]:
    available = [v for v in values if v is not None]
    return float(np.mean(available)) if available else None


def latex_table(header: list, rows: list, caption: str, label: str, left_columns: int = 1, fit_to_width: bool = False) -> str:
    """Booktabs table with the first left_columns left-aligned. A row of None adds vertical space (between motifs)."""
    lines = [
        "% Auto-generated by summarize_xai_results.py",
        "\\begin{table}[htbp]",
        "\\centering",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
    ]
    if fit_to_width:
        lines += ["\\setlength{\\tabcolsep}{4pt}", "\\resizebox{\\textwidth}{!}{%"]
    lines += [
        f"\\begin{{tabular}}{{{'l' * left_columns}{'c' * (len(header) - left_columns)}}}",
        "\\toprule",
        " & ".join(f"\\textbf{{{h}}}" for h in header) + " \\\\",
        "\\midrule",
    ]
    lines += ["\\addlinespace" if row is None else " & ".join(row) + " \\\\" for row in rows]
    lines += ["\\bottomrule", "\\end{tabular}%" if fit_to_width else "\\end{tabular}"]
    if fit_to_width:
        lines.append("}")
    lines.append("\\end{table}")
    return "\n".join(lines)


# =============================================================================
# Tables
# =============================================================================

def motif_table(summaries: dict, run_label: str, label_suffix: str) -> str:
    """
    One row per motif and substitution. Transcripts, sites and the control check depend only on the sequences,
    not on the model, so they are the same in every fold and are taken from the first fold with results.
    """
    folds = list(summaries)
    first_fold = next(iter(summaries.values()))["motifs"]
    header = ["Motif", "Subst.", "$n$", "Sites"] + [f"F{k}" for k in folds] + [
        "Mean $\\pm$ SD", "$>0$", "$\\Delta_M$", "$\\Delta_C$", "New",
    ]

    rows = []
    for motif in first_fold:
        if rows:
            rows.append(None)
        for i, sub in enumerate(first_fold[motif]["substitutions"]):
            per_fold = [s["motifs"][motif]["substitutions"].get(sub, {}) for s in summaries.values()]
            valid = [m for m in per_fold if m.get("n_transcripts", 0) > 0]
            motif_cell = motif if i == 0 else ""
            sub_cell = f"A$\\rightarrow${sub.split('>')[1]}"
            if not valid:
                rows.append([motif_cell, sub_cell, "0", "--"] + ["--"] * len(folds) + ["--", "--", "--", "--", "--"])
                continue

            def scaled(entry: dict, section: str, key: str = "mean_of_group_means") -> Optional[float]:
                return entry[section][key] * EFFECT_SCALE if entry.get("n_transcripts", 0) > 0 else None

            effects = [scaled(m, "effect") for m in per_fold]
            n_transcripts = valid[0]["n_transcripts"]
            control_changed = valid[0]["mutation_checks"]["transcripts_where_control_changed_site_count"]
            rows.append([
                motif_cell,
                sub_cell,
                f"{n_transcripts}",
                f"{valid[0]['sites_mutated_total'] / n_transcripts:.1f}",
                *[signed(e) for e in effects],
                mean_sd(effects, sign=True, decimals=1),
                f"{sum(e > 0 for e in effects if e is not None)}/{sum(e is not None for e in effects)}",
                signed(mean_or_none([scaled(m, "motif_shift_vs_base") for m in per_fold])),
                signed(mean_or_none([scaled(m, "base_effect_control_vs_base") for m in per_fold])),
                f"{100 * control_changed / n_transcripts:.1f}",
            ])

    caption = (
        f"Motif perturbation, {escape_latex(run_label)}. Each transcript is predicted three times: original sequence; motif "
        f"variant, in which the A of each motif site in the 3' UTR is replaced (sites where this would create a new site stay "
        f"unchanged); control variant, with the same substitution at equally many A's outside the motif sites. "
        f"$\\Delta_M$, $\\Delta_C$: mean shift of the motif variant and the control variant against the original prediction, "
        f"in units of $10^{{-3}}$. Any A substitution shifts the prediction, whether or not it hits a motif, so $\\Delta_M$ "
        f"alone does not isolate the motif; the effect is therefore $\\Delta_M - \\Delta_C$, which equals the prediction of the "
        f"motif variant $-$ the prediction of the control variant. Control positions are not drawn at random but matched: for "
        f"each mutated site, the nearest unused A in the 3' UTR that lies outside all sites of this motif and has the same "
        f"following base as the mutated A (DRACH: C, AUUUA: U, UGUANAUA: not constrained), so that both variants are comparable "
        f"in region, position and local context. Transcripts without enough such A's are excluded. "
        f"F0, F1, \\dots: effect per fold, in units of $10^{{-3}}$, mean over homology groups; a positive effect means that "
        f"the model treats the motif as destabilizing. SD over folds with a shared test set, not a confidence interval. "
        f"$n$: transcripts. Sites: mutated sites per transcript. $>0$: folds with a positive effect. "
        f"New: percentage of transcripts whose control mutation created motif sites."
    )
    return latex_table(header, rows, caption, f"tab:xai_motif_{label_suffix}", left_columns=2, fit_to_width=True)


def ablation_table(summaries: dict, run_label: str, label_suffix: str) -> str:
    """One row per channel: drop in Pearson r when the channel is set to zero."""
    folds = list(summaries)
    channels = next(iter(summaries.values()))["channel_names"]
    header = ["Channel"] + [f"Fold {k}" for k in folds] + ["Mean $\\pm$ SD"]

    rows = []
    for channel in channels:
        drops = [s["channel_ablation"].get(channel, {}).get("drop_pearson_r") for s in summaries.values()]
        rows.append([escape_latex(channel), *[unsigned(d) for d in drops], mean_sd(drops, sign=False, decimals=3)])

    baseline = [s["test_metrics"]["pearson_r"] for s in summaries.values()]
    caption = (
        f"Channel ablation, {escape_latex(run_label)}. Drop in Pearson r on the test set when the channel is set to zero "
        f"(baseline r = {mean_sd(baseline, sign=False, decimals=3)}). SD over folds with a shared test set, not a confidence interval."
    )
    return latex_table(header, rows, caption, f"tab:xai_ablation_{label_suffix}")


# =============================================================================
# CLI Main
# =============================================================================

def parse_args():
    default_dir = get_default_checkpoints_dir()
    parser = argparse.ArgumentParser(description="Creates LaTeX tables of the xAI results of fine-tuned Orthrus runs.")
    parser.add_argument("-d", "--base_dir", type=Path, default=default_dir, help=f"Directory to search recursively (default: {default_dir})")
    return parser.parse_args()


def main():
    args = parse_args()
    base_dir = args.base_dir.resolve()
    run_dirs = find_run_dirs(base_dir)
    if not run_dirs:
        print(f"[Error] No fold_*/{MOTIF_FILE} or fold_*/{ABLATION_FILE} found below {base_dir}.", file=sys.stderr)
        sys.exit(1)

    n_written = 0
    for run_dir in run_dirs:
        relative = run_dir.relative_to(base_dir).as_posix()
        run_label = run_dir.name if relative == "." else relative
        label_suffix = re.sub(r"[^A-Za-z0-9]+", "_", run_label)

        motif_summaries, motif_ignored = load_fold_summaries(run_dir, MOTIF_FILE, "motifs")
        ablation_summaries, ablation_ignored = load_fold_summaries(run_dir, ABLATION_FILE, "test_metrics")
        print(f"[Tables] {run_label}: motif perturbation in {len(motif_summaries)} folds, channel ablation in {len(ablation_summaries)} folds", file=sys.stderr)
        if motif_ignored or ablation_ignored:
            print(f"[Warning] {run_label}: ignored {motif_ignored} motif and {ablation_ignored} ablation files (older than the training or from an older script version).", file=sys.stderr)

        tables = []
        if motif_summaries:
            tables.append(motif_table(motif_summaries, run_label, label_suffix))
        if ablation_summaries:
            tables.append(ablation_table(ablation_summaries, run_label, label_suffix))
        if not tables:
            print(f"[Warning] {run_label}: all xAI results are outdated, no tables written. An existing {TABLES_FILE} is left unchanged.", file=sys.stderr)
            continue

        (run_dir / TABLES_FILE).write_text("\n\n".join(tables) + "\n", encoding="utf-8")
        (run_dir / DOCUMENT_FILE).write_text(DOCUMENT_TEMPLATE, encoding="utf-8")
        print(f"[Export] Saved {TABLES_FILE} and {DOCUMENT_FILE} to: {run_dir}", file=sys.stderr)
        n_written += 1

    if n_written == 0:
        print(f"[Error] All xAI results below {base_dir} are outdated, nothing to report.", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
